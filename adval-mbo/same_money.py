# -*- coding: utf-8 -*-
"""中野の自己資金を同額(6.10億)投じた場合の A:MBO / B:合併後買増し 比較"""
CASH = 6.10e8

# --- 共通前提 -------------------------------------------------
PX  = 229.0                 # SM株価(2026/9/21終値)
SM  = 12_105_900            # SM発行済
ADV_SHARES_SO = 201_616     # あどばる SO行使後 発行済
NAKANO_SO     = 74_000      # 中野(SO行使後)
ADV_EQ_LOI    = 18.0e8      # SMからのLOI評価

print('='*78)
print('前提: 中野の自己資金(中野ファンド含む) = {:.2f}億円 / SM株価 {:.0f}円'.format(CASH/1e8, PX))
print('='*78)

# --- A: MBO ---------------------------------------------------
print('\n【A】MBO（非上場のまま独立）')
print('  資金の行き先 : 会社（第三者割当増資）→ 純資産が増える')
print('  中野個人     :  74,000株 / 270,360株 = {:.3f}%'.format(74_000/270_360*100))
print('  中野ファンド :  61,180株 / 270,360株 = {:.3f}%  ← 6.10億'.format(61_180/270_360*100))
print('  中野陣営 計  : 135,180株 / 270,360株 = {:.3f}%   ★支配権あり'.format(135_180/270_360*100))
print('  取引後の会社 : 純資産 +3.90億 / 自己資本比率 24.9% / 有利子負債 6.07億')
print('  ビジョン借入 : 7.90億 → 全額返済（債権債務ゼロ）')

# --- B: 合併してから相対で買い増す ------------------------------
print('\n【B】合併 → 相対取得で買い増し')
new = round(ADV_EQ_LOI/PX)                 # 交付新株
tot = SM + new
per = new/ADV_SHARES_SO                    # あどばる1株あたり交付数
nak = NAKANO_SO*per
buy = CASH/PX                              # 6.10億で買える株数
print('  資金の行き先 : 売り手（重松氏/ビジョン）→ 会社の純資産は不変')
print('  合併後発行済 : {:,.0f}株 / 時価総額 {:.1f}億'.format(tot, tot*PX/1e8))
print('  中野(合併時) : {:,.0f}株 = {:.2f}%  (SO行使後)'.format(nak, nak/tot*100))
print('  6.10億で取得 : {:,.0f}株 = {:.2f}pt'.format(buy, buy/tot*100))
print('  → 買増し後  : {:,.0f}株 = {:.2f}%   ☆筆頭だが支配権なし'.format(nak+buy, (nak+buy)/tot*100))

need50 = tot*0.5 - nak
need33 = tot/3 - nak
print('\n  50%に必要な追加取得 : {:,.0f}株 = {:.2f}億円（市場価格ベース）'.format(need50, need50*PX/1e8))
print('  1/3に必要な追加取得 : {:,.0f}株 = {:.2f}億円 ← これを超える市場外買付はTOB必須'
      .format(need33, need33*PX/1e8))

# --- 誰から買うか --------------------------------------------
print('\n  6.10億で買える相手（合併後ベース・{:,.0f}株）:'.format(buy))
blocks = [('ダブルパインズ', 1_670_000), ('重松 大輔', 2_950_000),
          ('ビジョン（合併後持分）', round(tot*0.1926)), ('TKP', 2_550_000)]
for n, sh in blocks:
    print('    {:<22} {:>10,}株 = {:>5.2f}億円  {}'
          .format(n, sh, sh*PX/1e8, '← 6.10億で全量取得可' if sh*PX<=CASH else '（一部のみ）'))

# --- B': 合併後に第三者割当増資で入れる場合 ----------------------
print('\n【B’】合併 → 第三者割当増資で中野が引受（資金が会社に入る形）')
ns  = CASH/PX
tot2 = tot + ns
print('  発行新株     : {:,.0f}株 / 増資後発行済 {:,.0f}株'.format(ns, tot2))
print('  中野         : {:,.0f}株 = {:.2f}%   （Bより {:.2f}pt 低い）'
      .format(nak+ns, (nak+ns)/tot2*100, (nak+buy)/tot*100-(nak+ns)/tot2*100))
print('  希薄化率     : {:.1f}%  → 25%以上なら東証ルール上、株主総会決議または第三者意見が必要'
      .format(ns/tot*100))
print('  会社への効果 : 純資産 +6.10億（Bはゼロ）')

# --- 中野の手取り価値 -----------------------------------------
print('\n【参考】6.10億を投じた後に中野が握る株式の価値')
print('  A : 26.85億 × 50.000% = {:.2f}億（非上場・売却は限定的）'.format(26.85*0.5))
print('  B : {:.1f}億 × {:.2f}% = {:.2f}億（上場株・流動性あり）'
      .format(tot*PX/1e8, (nak+buy)/tot*100, tot*PX/1e8*(nak+buy)/tot))
