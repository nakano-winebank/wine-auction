"""必須条件3つ（①ビジョン株式の出口 ②借入7.90億の同時全額返済 ③中野が筆頭）を
   すべて満たす場合の必要資金と帰結"""
PX=229.0; OK=1e8
SM=12_105_900
SMH={'重松 大輔':2_950_000,'TKP':2_550_000,'ダブルパインズ':1_670_000,
     'CA・Startups2号':690_000,'鈴木 真一郎':530_000,'マイナビ':330_000,
     '東京建物':170_000,'XTech1号':170_000,'吉岡 裕之':130_000,'佐々木 正将':120_000,
     'その他':2_795_900}
ADV={'ビジョン':94_400,'中野 邦人':74_000,'BOS':10_000,'エアトリ':8_000,'KUMA':6_000,
     'フィル・カンパニー':4_000,'ベクトル':3_216,'アンビション':2_000}
ADV_TOT=201_616
EQ=18.0e8
new=round(EQ/PX); TOT=SM+new; per=new/ADV_TOT
nak=round(ADV['中野 邦人']*per); viz=round(ADV['ビジョン']*per)
oth=sum(round(v*per) for k,v in ADV.items() if k not in('中野 邦人','ビジョン'))
shige=SMH['重松 大輔']; dp=SMH['ダブルパインズ']

# 東証の流通株式から除外される保有者（役員・10%超・事業法人）
EXCL_BASE = shige+dp+SMH['TKP']+SMH['マイナビ']+SMH['東京建物']+SMH['佐々木 正将']+oth
def float_ratio(nakano_sh, vision_sh, to_market=0):
    excl = EXCL_BASE + nakano_sh + vision_sh
    return (TOT-excl)/TOT*100

print('='*78); print('必須条件：①ビジョン株式の出口 ②借入7.90億の同時全額返済 ③中野が筆頭株主')
print('='*78)
print('\n合併後 発行済 {:,}株 / 株価{:.0f}円 / 時価総額{:.1f}億'.format(TOT,PX,TOT*PX/OK))
print('  中野 {:,}株({:.2f}%) 重松 {:,}株({:.2f}%) ビジョン {:,}株({:.2f}%)'
      .format(nak,nak/TOT*100,shige,shige/TOT*100,viz,viz/TOT*100))

print('\n【A】MBO — 中野陣営を50.1%にして単独筆頭にする')
V=270_360
for r,lbl in ((0.500,'50.0%（同率）'),(0.501,'50.1%（単独筆頭）')):
    sh=round(V*r); fund=sh-74_000
    print('   {:<14} 中野陣営{:,}株 / 中野ファンド{:,}株 = {:.2f}億 / パートナー {:.2f}億'
          .format(lbl,sh,fund,fund*9964/OK,(V-sh)*9964/OK))
print('   ビジョンの受取: 株式 9.41億 ＋ 借入返済 7.90億 = 17.31億（同時決済）')
print('   あどばる有利子負債: 10.97億 → 6.07億（増資4.90億で圧縮＋みずほ3.00億リファイ）')
print('   流通株式比率: 非上場のため適用なし')

print('\n【B-1】合併 — 中野がビジョン株を全部買い取って筆頭になる')
cost=viz*PX; after=nak+viz
print('   中野の必要資金 : {:.2f}億（{:,}株）'.format(cost/OK,viz))
print('   取得後の中野   : {:,}株 = {:.2f}%  → 単独筆頭 ○'.format(after,after/TOT*100))
print('   1/3(33.33%)まで余裕 {:.2f}pt（{:,}株）※超えると市場外買付はTOB必須'
      .format(100/3-after/TOT*100, int(TOT/3-after)))
print('   流通株式比率   : {:.2f}%  ← 25%基準を下回る ×（ビジョン株が中野に移るだけ）'
      .format(float_ratio(after,0)))
print('   ビジョンの受取 : 株式 {:.2f}億（中野から）＋ 借入返済 7.90億 = {:.2f}億'.format(cost/OK,cost/OK+7.90))
print('   会社の借入     : ビジョン7.90億を全額リファイ → あどばる由来 10.97億のまま')

print('\n【B-2】合併 — ビジョン株は市場へ売出し、中野は重松と同数まで買う')
need_p = shige-nak; need_s = shige+dp-nak
print('   重松個人と同数 : {:,}株 = {:.2f}億 → 中野 {:.2f}%（重松と同率で筆頭）'
      .format(need_p,need_p*PX/OK,(nak+need_p)/TOT*100))
print('   重松側(DP込)と同数: {:,}株 = {:.2f}億 → 中野 {:.2f}%'
      .format(need_s,need_s*PX/OK,(nak+need_s)/TOT*100))
print('   流通株式比率   : {:.2f}%  ← ビジョン株{:.2f}%が市場に出るため基準クリア ○'
      .format(float_ratio(nak+need_p,0), viz/TOT*100))
print('   ビジョンの受取 : 売出し {:.2f}億（手数料・ディスカウント控除前）＋ 借入返済 7.90億'.format(cost/OK))
print('   会社の借入     : 同上 10.97億のまま')

