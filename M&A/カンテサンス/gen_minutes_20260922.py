def P(txt="",sz=10,b=False,color=None,before=0,after=4,ind=0,align=None):
    p=d.add_paragraph(); pf=p.paragraph_format
    pf.space_before=Pt(before); pf.space_after=Pt(after)
    if ind: pf.left_indent=Cm(ind)
    if align: p.alignment=align
    if txt:
        r=p.add_run(txt); r.font.size=Pt(sz); r.bold=b
        if color: r.font.color.rgb=color
    return p

def H1(t):
    p=P(t,sz=13,b=True,color=NAVY,before=14,after=6)
    return p

def H2(t):
    return P(t,sz=10.5,b=True,color=COPPER,before=9,after=3)

def bullet(t,ind=0.5):
    P("・"+t,ind=ind)

def kv(rows,widths=(4.0,12.0)):
    t=d.add_table(rows=0,cols=2); t.style='Table Grid'; t.alignment=WD_TABLE_ALIGNMENT.LEFT
    for k,v in rows:
        c=t.add_row().cells
        c[0].width=Cm(widths[0]); c[1].width=Cm(widths[1])
        for cell,txt,bold in ((c[0],k,True),(c[1],v,False)):
            pr=cell.paragraphs[0]; pr.paragraph_format.space_after=Pt(2)
            r=pr.add_run(txt); r.font.size=Pt(9.5); r.bold=bold; r.font.name='Meiryo'
            r._element.rPr.rFonts.set(qn('w:eastAsia'),'Meiryo')
    return t

