// ---- table helper (dual widths) ----
function tbl(colW, rows, opt={}) {
  const total = colW.reduce((a,b)=>a+b,0);
  return new Table({
    columnWidths: colW, width:{size:total, type:WidthType.DXA},
    borders:{
      top:{style:BorderStyle.SINGLE,size:4,color:LINE}, left:{style:BorderStyle.SINGLE,size:4,color:LINE},
      bottom:{style:BorderStyle.SINGLE,size:4,color:LINE}, right:{style:BorderStyle.SINGLE,size:4,color:LINE},
      insideHorizontal:{style:BorderStyle.SINGLE,size:4,color:LINE},
      insideVertical:{style:BorderStyle.SINGLE,size:4,color:LINE}
    },
    rows: rows.map((r,ri)=> new TableRow({
      cantSplit: true,
      children: r.map((c,ci)=> {
        const isHead = opt.head && ri===0;
        const cell = (typeof c === "object" && c!==null && "t" in c) ? c : {t:String(c)};
        return new TableCell({
          width:{size:colW[ci], type:WidthType.DXA},
          shading:(isHead||cell.shade)?{type:ShadingType.CLEAR, fill:cell.shade||HEAD, color:"auto"}:undefined,
          margins:{top:70, left:110, bottom:70, right:110},
          children:[new Paragraph({
            alignment: cell.align ?? (ci>0 && opt.rightNum ? AlignmentType.RIGHT : AlignmentType.LEFT),
            spacing:{after:0, line:280},
            children:[new TextRun({text:cell.t, font:(isHead||cell.gothic)?FG:F, size:cell.size??20, bold:isHead||cell.b, color:cell.c})]
          })]
        });
      })
    }))
  });
}

