# 高山社長ご指摘（2026-09-28メール）を匿名組合契約書に修正履歴付きで反映する
import re, html

SRC = "un/word/document.xml"
AUTHOR = "株式会社WineBank"
DATE = "2026-09-29T00:00:00Z"
x = open(SRC, encoding="utf-8").read()

_id = [9000]
def nid():
    _id[0] += 1
    return _id[0]

def esc(t): return html.escape(t, quote=False)

RPR = '<w:rPr><w:rFonts w:ascii="ＭＳ 明朝" w:hAnsi="ＭＳ 明朝" w:hint="eastAsia"/></w:rPr>'
RPR_B = '<w:rPr><w:rFonts w:ascii="ＭＳ 明朝" w:hAnsi="ＭＳ 明朝" w:hint="eastAsia"/><w:b/></w:rPr>'

def ins_run(text, rpr=RPR):
    return (f'<w:ins w:id="{nid()}" w:author="{AUTHOR}" w:date="{DATE}"><w:r>{rpr}'
            f'<w:t xml:space="preserve">{esc(text)}</w:t></w:r></w:ins>')

def del_run(text, rpr=RPR):
    return (f'<w:del w:id="{nid()}" w:author="{AUTHOR}" w:date="{DATE}"><w:r>{rpr}'
            f'<w:delText xml:space="preserve">{esc(text)}</w:delText></w:r></w:del>')

# ─────────────────────────────── 段落の取得
def paras():
    return [(m.start(), m.end()) for m in re.finditer(r'<w:p[ >].*?</w:p>', x, re.S)]

def ptext(p): return ''.join(re.findall(r'<w:t[^>]*>([^<]*)</w:t>', p))

def find_para(needle, nth=0):
    hits = [(a, b) for a, b in paras() if needle in ptext(x[a:b])]
    assert len(hits) > nth, f"段落が見つからない: {needle}"
    return hits[nth]

# ─────────────────────────────── 段落内の置換（修正履歴）
def edit(para_needle, anchor, new=None, delete=None, where="after", nth=0):
    """anchor を含む w:t を分割し、anchor の前/後に挿入、または delete を削除して new を挿入する。"""
    global x
    a, b = find_para(para_needle, nth)
    p = x[a:b]
    target = delete if delete else anchor
    for rm in re.finditer(r'<w:r>(<w:rPr>.*?</w:rPr>)?(.*?)</w:r>', p, re.S):
        rpr, body = rm.group(1) or "", rm.group(2)
        for tm in re.finditer(r'<w:t(?: [^>]*)?>([^<]*)</w:t>', body):
            txt = html.unescape(tm.group(1))
            if target not in txt:
                continue
            i = txt.index(target)
            if delete:
                pre, post = txt[:i], txt[i + len(delete):]
                mid = del_run(delete, rpr) + (ins_run(new, rpr) if new else "")
            elif where == "after":
                pre, post = txt[:i + len(anchor)], txt[i + len(anchor):]
                mid = ins_run(new, rpr)
            else:
                pre, post = txt[:i], txt[i:]
                mid = ins_run(new, rpr)
            before, after = body[:tm.start()], body[tm.end():]
            parts = []
            if before or pre:
                parts.append(f'<w:r>{rpr}{before}<w:t xml:space="preserve">{esc(pre)}</w:t></w:r>')
            parts.append(mid)
            if post or after:
                parts.append(f'<w:r>{rpr}<w:t xml:space="preserve">{esc(post)}</w:t>{after}</w:r>')
            newp = p[:rm.start()] + ''.join(parts) + p[rm.end():]
            x = x[:a] + newp + x[b:]
            return
    raise AssertionError(f"文字列が見つからない: {target} in {para_needle}")

# ─────────────────────────────── 新しい段落（修正履歴）
PPR_ITEM  = '<w:pPr><w:tabs><w:tab w:val="left" w:pos="518"/></w:tabs><w:ind w:left="518" w:hanging="518"/>{rpr}</w:pPr>'
PPR_SUB   = '<w:pPr><w:tabs><w:tab w:val="left" w:pos="1260"/></w:tabs><w:ind w:left="1260" w:hanging="742"/>{rpr}</w:pPr>'
PPR_HEAD  = '<w:pPr><w:keepNext/>{rpr}</w:pPr>'
PPR_PLAIN = '<w:pPr>{rpr}</w:pPr>'
PPR_CTR   = '<w:pPr><w:jc w:val="center"/>{rpr}</w:pPr>'

def mark():
    return (f'<w:rPr><w:ins w:id="{nid()}" w:author="{AUTHOR}" w:date="{DATE}"/>'
            '<w:rFonts w:ascii="ＭＳ 明朝" w:hAnsi="ＭＳ 明朝"/></w:rPr>')

def P(kind, text="", num=None, bold=False):
    ppr = {"item": PPR_ITEM, "sub": PPR_SUB, "head": PPR_HEAD,
           "plain": PPR_PLAIN, "center": PPR_CTR}[kind].format(rpr=mark())
    rpr = RPR_B if bold else RPR
    if not text and num is None:
        return f'<w:p>{ppr}</w:p>'
    inner = ""
    if num is not None:
        inner += f'<w:t xml:space="preserve">{esc(num)}</w:t><w:tab/>'
    inner += f'<w:t xml:space="preserve">{esc(text)}</w:t>'
    return (f'<w:p>{ppr}<w:ins w:id="{nid()}" w:author="{AUTHOR}" w:date="{DATE}">'
            f'<w:r>{rpr}{inner}</w:r></w:ins></w:p>')

def PAGEBREAK():
    return (f'<w:p><w:pPr>{mark()}</w:pPr><w:ins w:id="{nid()}" w:author="{AUTHOR}" w:date="{DATE}">'
            f'<w:r><w:br w:type="page"/></w:r></w:ins></w:p>')

def insert_after(para_needle, blocks, nth=0):
    global x
    a, b = find_para(para_needle, nth)
    x = x[:b] + ''.join(blocks) + x[b:]

def insert_before_sectpr(blocks):
    global x
    i = x.rindex('<w:sectPr')
    x = x[:i] + ''.join(blocks) + x[i:]

def replace_para_body(para_needle, new):
    """段落内の既存 run をすべて削除扱いにし、新しい文を挿入する。"""
    global x
    a, b = find_para(para_needle)
    p = x[a:b]
    k = p.index('</w:pPr>') + len('</w:pPr>')
    head, body = p[:k], p[k:-len('</w:p>')]
    def to_del(m):
        r = m.group(0).replace('<w:t>', '<w:delText xml:space="preserve">').replace('<w:t xml:space="preserve">', '<w:delText xml:space="preserve">').replace('</w:t>', '</w:delText>')
        return f'<w:del w:id="{nid()}" w:author="{AUTHOR}" w:date="{DATE}">{r}</w:del>'
    body = re.sub(r'<w:r>.*?</w:r>', to_del, body, flags=re.S)
    x = x[:a] + head + body + ins_run(new) + '</w:p>' + x[b:]

