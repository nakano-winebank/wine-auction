def xnpv(r,c):
    t0=c[0][0]; return sum(v/((1+r)**((d-t0).days/365.0)) for d,v in c)
def xirr(c):
    r=0.0; prev=xnpv(r,c); lo=None
    while r<60:
        r2=r+0.002; cur=xnpv(r2,c)
        if prev*cur<0: lo,hi=r,r2; break
        prev=cur; r=r2
    if lo is None: return None
    for _ in range(200):
        m=(lo+hi)/2
        if xnpv(lo,c)*xnpv(m,c)<=0: hi=m
        else: lo=m
    return (lo+hi)/2
